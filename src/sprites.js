// Helper to pre-render 16x16 sprite matrix to offscreen Canvas
function createPixelCanvas(matrix, scale = 2) {
  const c = document.createElement('canvas');
  c.width = 16 * scale;
  c.height = 16 * scale;
  const ctx = c.getContext('2d');
  for (let r = 0; r < 16; r++) {
    for (let col = 0; col < 16; col++) {
      const colorId = matrix[r][col];
      const color = PALETTE[colorId];
      if (color) {
        ctx.fillStyle = color;
        ctx.fillRect(col * scale, r * scale, scale, scale);
      }
    }
  }
  return c;
}

